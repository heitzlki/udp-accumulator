// PS7 stub with every input tied off (AXI clocks to the fabric clock,
// active-low signals high, the rest low), generated from the PS7 port list
// in yosys's cells_xtra.v - except GEM1's EMIO GMII and the M_AXI_GP0
// port, which are wired out as module ports. Without a PS7 instance the
// PS-PL interface is left unconfigured and Linux hangs when the bitstream
// loads. clk must be the 25 MHz MII clock: it drives both GEM1
// GMII clocks and MAXIGP0ACLK, keeping the whole design in one clock domain.
module ps7_enet (
    input  wire        clk,
    // GEM1 GMII: PS transmit -> fabric (the fabric is "the wire")
    output wire [7:0]  gem_txd,
    output wire        gem_tx_en,
    output wire        gem_tx_er,
    // fabric -> PS receive
    input  wire [7:0]  gem_rxd,
    input  wire        gem_rx_dv,
    input  wire        gem_rx_er,
    // M_AXI_GP0 (AXI3), CPU master, slave regs at 0x4000_0000
    output wire [31:0] gp0_awaddr,
    output wire        gp0_awvalid,
    input  wire        gp0_awready,
    output wire [11:0] gp0_awid,
    output wire [31:0] gp0_wdata,
    output wire [3:0]  gp0_wstrb,
    output wire        gp0_wvalid,
    output wire        gp0_wlast,
    input  wire        gp0_wready,
    input  wire [11:0] gp0_bid,
    input  wire [1:0]  gp0_bresp,
    input  wire        gp0_bvalid,
    output wire        gp0_bready,
    output wire [31:0] gp0_araddr,
    output wire        gp0_arvalid,
    input  wire        gp0_arready,
    output wire [11:0] gp0_arid,
    output wire [3:0]  gp0_arlen,
    input  wire [31:0] gp0_rdata,
    input  wire [11:0] gp0_rid,
    input  wire [1:0]  gp0_rresp,
    input  wire        gp0_rlast,
    input  wire        gp0_rvalid,
    output wire        gp0_rready
);
